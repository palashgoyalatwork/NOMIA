# ============================================================
# GET CITIES
# ============================================================

def get_cities(country):
    """
    Return the cities available for a country.
    """

    return COUNTRIES.get(country, [])


# ============================================================
# CHECK CITY
# ============================================================

def city_exists(country, city):
    """
    Check whether a city exists under a country.
    """

    return city in COUNTRIES.get(country, [])


# ============================================================
# FIND COUNTRY FROM CITY
# ============================================================

def get_country_for_city(city):
    """
    Return the country associated with a city.

    Returns None if the city is not registered.
    """

    for country, cities in COUNTRIES.items():

        if city in cities:
            return country

    return None


# ============================================================
# TOTAL COUNTRIES
# ============================================================

def total_countries():
    """
    Return total number of countries.
    """

    return len(COUNTRIES)


# ============================================================
# TOTAL CITIES
# ============================================================

def total_cities():
    """
    Return total number of registered cities.
    """

    return sum(
        len(cities)
        for cities in COUNTRIES.values()
    )